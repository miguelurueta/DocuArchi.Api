using System.Diagnostics;
using MiApp.Services.Service.GestorDocumental.Editor;
using MiApp.Services.Service.Seguridad.Autorizacion.CurrentClaim;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace DocuArchi.Api.Controllers.GestorDocumental.Editor;

/// <summary>Provides authenticated access to editor image bytes stored in the company database.</summary>
[ApiController]
[Authorize]
[Route("api/gestor-documental/editor/images")]
public sealed class SolicitaEditorImageContentController : ControllerBase
{
    private readonly IClaimValidationService _claimValidationService;
    private readonly IServiceSolicitaEditorImageContent _service;
    private readonly ILogger<SolicitaEditorImageContentController> _logger;

    public SolicitaEditorImageContentController(
        IClaimValidationService claimValidationService,
        IServiceSolicitaEditorImageContent service,
        ILogger<SolicitaEditorImageContentController> logger)
    {
        _claimValidationService = claimValidationService;
        _service = service;
        _logger = logger;
    }

    /// <summary>Returns the original bytes of an active editor image.</summary>
    /// <param name="imageUid">Opaque image GUID generated by the upload endpoint.</param>
    /// <param name="cancellationToken">Request cancellation.</param>
    /// <returns>Binary image content or a safe AppResponses error envelope.</returns>
    [HttpGet("{imageUid}/content")]
    [Produces("image/png", "image/jpeg", "image/webp", "application/json")]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status304NotModified)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    [ProducesResponseType(StatusCodes.Status409Conflict)]
    [ProducesResponseType(StatusCodes.Status500InternalServerError)]
    public async Task<IActionResult> GetContent(
        [FromRoute] string imageUid,
        CancellationToken cancellationToken)
    {
        var started = Stopwatch.GetTimestamp();
        var requestId = EditorImageContentErrorResponseFactory.EnsureRequestId(HttpContext.TraceIdentifier);
        SetSecurityHeaders();
        _logger.LogInformation(
            "Editor image request started. RequestId={RequestId} UserId={UserId} ImageUidHash={ImageUidHash} StorageTypeCode={StorageTypeCode} ContentType={ContentType} PersistedSize={PersistedSize} ActualSize={ActualSize} HttpStatus={HttpStatus} ErrorCode={ErrorCode} Stage={Stage} DurationMs={DurationMs} MetaStatus={MetaStatus}",
            requestId,
            User.FindFirst("idUsuario")?.Value,
            ServiceSolicitaEditorImageContent.HashUid(imageUid),
            null, null, null, null, null, null,
            "start",
            0,
            "started");

        var claim = _claimValidationService.ValidateClaim<string>("defaulalias");
        if (!claim.Success || string.IsNullOrWhiteSpace(claim.ClaimValue))
        {
            return Error(EditorImageContentErrorCatalog.ClaimInvalid, requestId, imageUid, started, "claims");
        }

        var result = await _service
            .GetAsync(imageUid, claim.ClaimValue, cancellationToken)
            .ConfigureAwait(false);

        if (result.Status != EditorImageContentStatus.Success ||
            result.Bytes is null ||
            result.ContentType is null ||
            result.ImageUid is null)
        {
            var code = result.ErrorCode ?? EditorImageContentErrorCatalog.ReadFailed;
            return Error(code, requestId, imageUid, started, "service");
        }

        var etag = $"\"{result.ImageUid}\"";
        Response.Headers["ETag"] = etag;
        Response.Headers["Content-Disposition"] = "inline";

        if (Request.Headers.IfNoneMatch.Any(value =>
                string.Equals(value?.Trim(), etag, StringComparison.Ordinal)))
        {
            LogOutcome(
                requestId,
                imageUid,
                result,
                StatusCodes.Status304NotModified,
                null,
                "conditional_get",
                started);
            return StatusCode(StatusCodes.Status304NotModified);
        }

        Response.ContentLength = result.ContentLength;
        LogOutcome(requestId, imageUid, result, StatusCodes.Status200OK, null, "success", started);
        return File(result.Bytes, result.ContentType);
    }

    private ObjectResult Error(
        string code,
        string requestId,
        string? imageUid,
        long started,
        string stage)
    {
        var status = EditorImageContentErrorResponseFactory.ResolveHttpStatus(code);
        var descriptor = EditorImageContentErrorDescriptors.Resolve(code);
        _logger.Log(
            status >= 500 ? LogLevel.Error : LogLevel.Warning,
            "Editor image request failed. RequestId={RequestId} UserId={UserId} ImageUidHash={ImageUidHash} StorageTypeCode={StorageTypeCode} ContentType={ContentType} PersistedSize={PersistedSize} ActualSize={ActualSize} HttpStatus={HttpStatus} ErrorCode={ErrorCode} Stage={Stage} DurationMs={DurationMs} MetaStatus={MetaStatus}",
            requestId,
            User.FindFirst("idUsuario")?.Value,
            ServiceSolicitaEditorImageContent.HashUid(imageUid),
            null,
            null,
            null,
            null,
            status,
            code,
            stage,
            Stopwatch.GetElapsedTime(started).TotalMilliseconds,
            descriptor.MetaStatus);

        return StatusCode(status, EditorImageContentErrorResponseFactory.Build<object?>(code, requestId));
    }

    private void LogOutcome(
        string requestId,
        string imageUid,
        EditorImageContentResult result,
        int status,
        string? errorCode,
        string stage,
        long started)
    {
        _logger.LogInformation(
            "Editor image request completed. RequestId={RequestId} UserId={UserId} ImageUidHash={ImageUidHash} StorageTypeCode={StorageTypeCode} ContentType={ContentType} PersistedSize={PersistedSize} ActualSize={ActualSize} HttpStatus={HttpStatus} ErrorCode={ErrorCode} Stage={Stage} DurationMs={DurationMs} MetaStatus={MetaStatus}",
            requestId,
            User.FindFirst("idUsuario")?.Value,
            ServiceSolicitaEditorImageContent.HashUid(imageUid),
            result.StorageTypeCode,
            result.ContentType,
            result.PersistedFileSize,
            result.ContentLength,
            status,
            errorCode,
            stage,
            Stopwatch.GetElapsedTime(started).TotalMilliseconds,
            status == StatusCodes.Status304NotModified ? "not_modified" : "success");
    }

    private void SetSecurityHeaders()
    {
        Response.Headers["X-Content-Type-Options"] = "nosniff";
        Response.Headers["Cache-Control"] = "private, no-cache";
        Response.Headers["Content-Security-Policy"] = "default-src 'none'; sandbox";
    }
}
